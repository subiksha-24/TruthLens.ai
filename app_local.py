# ==================================================
# SOURCE VERIFICATION
# ==================================================

def run_verification():

    data = request.get_json(silent=True)

    if not data:
        return jsonify({
            "error": "No verification data received."
        }), 400

    url = data.get("url", "").strip()

    # --------------------------------------------------
    # No URL
    # --------------------------------------------------

    if not url:
        return jsonify({
            "success": False,
            "status": "NO_SOURCE",
            "message": "No article URL was provided.",
            "source_accessible": False,
            "title": "",
            "text_preview": ""
        })

    # --------------------------------------------------
    # Basic URL validation
    # --------------------------------------------------

    parsed = urlparse(url)

    if parsed.scheme not in ["http", "https"]:
        return jsonify({
            "success": False,
            "status": "INVALID_URL",
            "message": "The supplied source URL is not valid.",
            "source_accessible": False,
            "title": "",
            "text_preview": ""
        }), 400

    # --------------------------------------------------
    # Try to access source
    # --------------------------------------------------

    try:

        headers = {
            "User-Agent":
                "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                "AppleWebKit/537.36 "
                "(KHTML, like Gecko) "
                "Chrome/150.0 Safari/537.36"
        }

        response = requests.get(
            url,
            headers=headers,
            timeout=10
        )

        # --------------------------------------------------
        # HTTP error
        # --------------------------------------------------

        if response.status_code >= 400:
            return jsonify({
                "success": False,
                "status": "SOURCE_ERROR",
                "message":
                    "The source returned HTTP status "
                    + str(response.status_code)
                    + ".",
                "source_accessible": False,
                "title": "",
                "text_preview": ""
            })

        # --------------------------------------------------
        # Parse webpage
        # --------------------------------------------------

        soup = BeautifulSoup(
            response.text,
            "html.parser"
        )

        # Remove unnecessary elements
        for element in soup(
            ["script", "style", "noscript"]
        ):
            element.decompose()

        # Get page title
        title = ""

        if soup.title:
            title = soup.title.get_text(
                strip=True
            )

        # Get visible text
        page_text = soup.get_text(
            separator=" ",
            strip=True
        )

        # Clean whitespace
        page_text = " ".join(
            page_text.split()
        )

        # Create preview
        text_preview = page_text[:1000]

        # --------------------------------------------------
        # Successful retrieval
        # --------------------------------------------------

        return jsonify({
            "success": True,
            "status": "SOURCE_ACCESSIBLE",
            "message":
                "The article page was successfully accessed.",
            "source_accessible": True,
            "title": title,
            "text_preview": text_preview,
            "source_url": url
        })

    # --------------------------------------------------
    # Connection error
    # --------------------------------------------------

    except requests.exceptions.RequestException as error:

        print("Source request error:", error)

        return jsonify({
            "success": False,
            "status": "SOURCE_UNAVAILABLE",
            "message":
                "TruthLens could not access this source.",
            "source_accessible": False,
            "title": "",
            "text_preview": ""
        })

    # --------------------------------------------------
    # Unexpected error
    # --------------------------------------------------

    except Exception as error:

        print("Verification error:", error)

        return jsonify({
            "success": False,
            "status": "VERIFICATION_ERROR",
            "message":
                "An unexpected error occurred while checking the source.",
            "source_accessible": False,
            "title": "",
            "text_preview": ""
        })


