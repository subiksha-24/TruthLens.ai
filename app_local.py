# ==================================================
# PREDICTION FUNCTION
# ==================================================

def run_prediction():

    data = request.get_json(silent=True)

    if not data:
        return jsonify({
            "error": "No data received."
        }), 400

    text = data.get("text", "").strip()
    url = data.get("url", "").strip()

    if not text:
        return jsonify({
            "error": "Please enter a news claim."
        }), 400

    # Convert text into numerical format
    text_vector = vectorizer.transform([text])

    # ML prediction
    prediction = model.predict(text_vector)[0]

    # Prediction probabilities
    probabilities = model.predict_proba(text_vector)[0]

    fake_probability = float(probabilities[0])
    real_probability = float(probabilities[1])

    # ==================================================
    # DETERMINE VERDICT
    # ==================================================

    if prediction == 0:

        confidence = fake_probability

        if confidence >= 0.65:
            result = "FAKE"
        else:
            result = "UNCERTAIN"

    else:

        confidence = real_probability

        if confidence >= 0.65:
            result = "REAL"
        else:
            result = "UNCERTAIN"

    confidence_percentage = round(confidence * 100, 2)

    # ==================================================
    # SEND RESULT
    # ==================================================

    return jsonify({
        "result": result,
        "confidence": confidence_percentage,
        "fake_probability": round(fake_probability * 100, 2),
        "real_probability": round(real_probability * 100, 2),
        "article_url": url,
        "message": "Prediction generated by the TruthLens machine-learning model."
    })


# ==================================================
# PREDICTION API
# ==================================================

@app.route("/predict", methods=["POST"])
def predict():
    return run_prediction()


